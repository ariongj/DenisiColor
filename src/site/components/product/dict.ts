/** "1 paket / 2 paketa", "1 pako", "1 pack / 2 packs". */
export function packWord(n: number, lang: Lang, one: string, many: string) {
  if (lang === 'en') return n === 1 ? one : many;
  if (lang === 'me') return n % 10 === 1 && n % 100 !== 11 ? one : many;
  return one;
}

/** Money with cents only when needed ("289 €", "241,98 €"); `target` keeps the format stable while a tween runs. */
export function eur(v: number, lang: Lang, target = v) {
  return money(v, lang, { decimals: Math.round(target * 100) % 100 !== 0 });
}
